-- Shared Identity's effective relational schema at the Carelog dev V6 boundary.
-- This is a fresh Identity baseline, not a copy of Carelog's product migration history.

CREATE TABLE platform_accounts (
    id uuid NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'ACTIVE',
    primary_email character varying(255),
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT platform_accounts_pkey PRIMARY KEY (id),
    CONSTRAINT platform_accounts_status_check CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE password_credentials (
    account_id uuid NOT NULL,
    login_id character varying(255) NOT NULL,
    password_hash character varying(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT password_credentials_pkey PRIMARY KEY (account_id),
    CONSTRAINT password_credentials_login_id_key UNIQUE (login_id),
    CONSTRAINT fk_password_credentials_account
        FOREIGN KEY (account_id) REFERENCES platform_accounts(id)
);

CREATE TABLE external_identities (
    id bigint GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME external_identities_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ) NOT NULL,
    account_id uuid NOT NULL,
    provider character varying(50) NOT NULL,
    provider_subject character varying(255) NOT NULL,
    email_snapshot character varying(255),
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT external_identities_pkey PRIMARY KEY (id),
    CONSTRAINT external_identities_provider_subject_key UNIQUE (provider, provider_subject),
    CONSTRAINT fk_external_identities_account
        FOREIGN KEY (account_id) REFERENCES platform_accounts(id)
);

CREATE INDEX idx_external_identities_account_id ON external_identities(account_id);

CREATE TABLE refresh_token (
    refresh_token_id bigint GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME refresh_token_refresh_token_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ) NOT NULL,
    refresh_token character varying(500) NOT NULL,
    account_id uuid NOT NULL,
    user_id character varying(255),
    token_expires_at timestamp(6) with time zone NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    created_by character varying(255),
    updated_by character varying(255),
    CONSTRAINT refresh_token_pkey PRIMARY KEY (refresh_token_id),
    CONSTRAINT refresh_token_refresh_token_key UNIQUE (refresh_token),
    CONSTRAINT fk_refresh_token_account
        FOREIGN KEY (account_id) REFERENCES platform_accounts(id)
);

CREATE INDEX idx_refresh_token_account_id ON refresh_token(account_id);

CREATE TABLE product_clients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id character varying(100) NOT NULL,
    product character varying(50) NOT NULL,
    channel character varying(50) NOT NULL,
    enabled boolean NOT NULL,
    created_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_product_clients_client_id UNIQUE (client_id),
    CONSTRAINT chk_product_clients_client_id_format
        CHECK (client_id ~ '^[a-z0-9][a-z0-9._-]{0,99}$'),
    CONSTRAINT chk_product_clients_product
        CHECK (product IN ('CARELOG', 'FINANCE_HARNESS', 'DEV_HARNESS')),
    CONSTRAINT chk_product_clients_channel
        CHECK (channel IN ('WEB', 'MOBILE', 'IOS', 'ANDROID'))
);

